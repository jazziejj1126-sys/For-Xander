let currentLetter = 1;


function openLetters() {

    document.getElementById("letters")
        .scrollIntoView({
            behavior: "smooth"
        });

}


function openLetter(number) {

    currentLetter = number;

    document.getElementById("letters")
        .style.display = "none";

    document.getElementById("home")
        .style.display = "none";

    document.getElementById("reader")
        .classList.add("active");

    showLetter(number);

}


function showLetter(number) {

    const letter = letters[number];

    document.getElementById("letterNumber")
        .textContent = "LETTER " + String(number).padStart(2, "0");

    document.getElementById("letterTitle")
        .textContent = letter.title;

    document.getElementById("letterContent")
        .innerHTML = letter.content;

    window.scrollTo(0, 0);

}


function closeLetter() {

    document.getElementById("reader")
        .classList.remove("active");

    document.getElementById("letters")
        .style.display = "block";

    document.getElementById("home")
        .style.display = "flex";

    document.getElementById("letters")
        .scrollIntoView({
            behavior: "smooth"
        });

}


function nextLetter() {

    if (currentLetter < 12) {
        currentLetter++;
        showLetter(currentLetter);
    }

}


function previousLetter() {

    if (currentLetter > 1) {
        currentLetter--;
        showLetter(currentLetter);
    }

}
