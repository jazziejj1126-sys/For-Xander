let currentLetter = 1;

function openLetters() {
  const home = document.getElementById("home");
  const lettersPage = document.getElementById("letters");

  if (home) home.style.display = "none";
  if (lettersPage) lettersPage.style.display = "block";

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}


function openLetter(number) {
  const letter = letters[number];

  if (!letter) {
    console.error("Letter not found:", number);
    return;
  }

  currentLetter = number;

  const home = document.getElementById("home");
  const lettersPage = document.getElementById("letters");
  const reader = document.getElementById("reader");

  const letterNumber = document.getElementById("letterNumber");
  const letterTitle = document.getElementById("letterTitle");
  const letterContent = document.getElementById("letterContent");

  if (home) home.style.display = "none";
  if (lettersPage) lettersPage.style.display = "none";
  if (reader) reader.style.display = "block";

  if (letterNumber) {
    letterNumber.textContent =
      "LETTER " + String(number).padStart(2, "0");
  }

  if (letterTitle) {
    letterTitle.textContent = letter.title;
  }

  if (letterContent) {
    letterContent.innerHTML = letter.content;
  }

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}


function closeLetter() {
  const reader = document.getElementById("reader");
  const lettersPage = document.getElementById("letters");

  if (reader) reader.style.display = "none";
  if (lettersPage) lettersPage.style.display = "block";

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}


function nextLetter() {
  if (currentLetter < 20) {
    openLetter(currentLetter + 1);
  }
}


function previousLetter() {
  if (currentLetter > 1) {
    openLetter(currentLetter - 1);
  }
}
